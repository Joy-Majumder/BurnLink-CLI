#!/usr/bin/env node
// Build-time: read keys/issuer.pub and write its contents into
// src/issuer-pub.js as an exported string constant. This lets the
// pkg-built binary carry the public key without needing to bundle
// a file via static analysis.

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const pubPath = path.join(__dirname, "..", "keys", "issuer.pub");
const outPath = path.join(__dirname, "..", "src", "issuer-pub.js");

if (!fs.existsSync(pubPath)) {
  console.error(`error: missing ${pubPath}. Run bin/gen-issuer.js first.`);
  process.exit(1);
}

const pem = fs.readFileSync(pubPath, "utf8");
const js = `// AUTO-GENERATED by bin/embed-issuer-pub.js — do not edit.\n` +
  `module.exports = ${JSON.stringify(pem)};\n`;
fs.writeFileSync(outPath, js);
console.log(`✓ wrote ${outPath} (${pem.length} bytes)`);
